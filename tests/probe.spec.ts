import { test, expect } from '@playwright/test';
test('dragging the 3D probe samples a new point without advancing simulation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('./#simulation');
  await page.locator('#scene').scrollIntoViewIfNeeded();
  await expect(page.locator('#scene')).toHaveAttribute('data-rendered', 'true');
  await page.getByRole('button', { name: '三维 · 圆柱绕流' }).click();
  await expect(page.locator('#scene')).toHaveAttribute('data-kind', 'cylinder');
  await expect(page.locator('#scene')).toHaveAttribute('data-rendered', 'true');
  const handle = page.getByRole('button', { name: '移动三维探针', exact: true });
  await expect(handle).toBeVisible();
  const before = await page.locator('#probe-location').textContent();
  const box = (await handle.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 55, box.y + box.height / 2 + 25, { steps: 8 });
  await page.mouse.up();
  await expect(page.locator('#probe-location')).not.toHaveText(before!);
  await expect(page.locator('#scene')).toHaveAttribute('data-steps', '0');
  await page.getByText('流动是怎样算出来的？').click();
  await expect(page.locator('#populations>div')).toHaveCount(19);
  const moved = (await page.locator('#probe-location').textContent())!.match(/\d+/g)!.map(Number);
  await handle.focus();
  await page.keyboard.press('PageUp');
  await expect(page.locator('#probe-location')).toHaveText(`尾迹探针（${moved[0]}，${moved[1]}，${Math.min(18, moved[2] + 1)}）`);
  await page.locator('#expand-fluid').click();
  const expandedBefore = await page.locator('#probe-location').textContent();
  const expandedBox = (await handle.boundingBox())!;
  await page.mouse.move(expandedBox.x + 12, expandedBox.y + 12);
  await page.mouse.down();
  await page.mouse.move(expandedBox.x + 67, expandedBox.y + 32, { steps: 8 });
  await page.mouse.up();
  await expect(page.locator('#probe-location')).not.toHaveText(expandedBefore!);
  await expect(page.locator('#scene')).toHaveAttribute('data-steps', '0');
});
